<?php

namespace Ycore\Exceptions;

use Illuminate\Database\Eloquent\ModelNotFoundException;
use Illuminate\Foundation\Exceptions\Handler as ExceptionHandler;
use Psr\Log\LoggerInterface;
use Symfony\Component\HttpKernel\Exception\MethodNotAllowedHttpException;
use Throwable;
use Ycore\Jobs\EmailJob;
use Ycore\Models\ErrorAccess;

class Handler extends ExceptionHandler
{

    /**
     * A list of exception types with their corresponding custom log levels.
     *
     * @var array<class-string<\Throwable>, \Psr\Log\LogLevel::*>
     */
    protected $levels = [
        //
    ];

    /**
     * A list of the exception types that are not reported.
     *
     * @var array<int, class-string<\Throwable>>
     */
    protected $dontReport = [
        //
    ];

    /**
     * A list of the inputs that are never flashed to the session on validation exceptions.
     *
     * @var array<int, string>
     */
    protected $dontFlash = [
        'current_password',
        'password',
        'password_confirmation',
    ];


    public function render($request, Throwable $e)
    {


        $er = parent::render($request, $e);

        if ($er->getStatusCode() === 429) {
            return response('访问过于频繁', 429);
        }


        try {


            if ($er->getStatusCode() === 404 || $e instanceof MethodNotAllowedHttpException || ((env('APP_DEBUG') === false && !app()->runningInConsole()) && ($e instanceof ModelNotFoundException || $e->getPrevious() instanceof ModelNotFoundException))) {


                return response()->view('404', [], 404);


            }

        } catch (Throwable $exception) {


            return response('404', 404);

        } finally {

            try {
                ErrorAccess::create([
                    'ip' => $request->ip(),
                    'url' => $request->fullUrl(),
                    'referer' => $request->header('referer'),
                    'query' => $request->getQueryString(),
                    'agent' => $request->header('user-agent', "")
                ]);
            } catch (Throwable $recordError) {
                $this->recordSecondaryFailure('记录错误访问', $recordError);
            }

        }


        try {

            if (!env('APP_DEBUG')) {


                return response()->view('500', [], $er->getStatusCode());


            }


            return $er; // TODO: Change the autogenerated stub


        } catch (Throwable $exception) {


            return response($er->getStatusCode(), $er->getStatusCode());


        } finally {

            try {
                $notice_email = getOption('notice_mail');
                if ($notice_email) {
                    // Laravel checks the optional renderer and falls back to Symfony.
                    $view = $this->renderExceptionContent($e);
                    dispatch(new EmailJob([$notice_email], env('APP_NAME') . "-报错日志(状态码" . $er->getStatusCode() . ")-" . date("Y-m-d-H-i-s"),
                        $e->getMessage() ?: "无错误信息", 'error.html', $view ?: "空数据"));
                }
            } catch (Throwable $notificationError) {
                $this->recordSecondaryFailure('发送错误通知', $notificationError);
            }

        }


    }

    protected function recordSecondaryFailure(string $operation, Throwable $error): void
    {
        try {
            $this->container->make(LoggerInterface::class)->warning($operation . '失败，保留原异常响应', ['exception' => $error]);
        } catch (Throwable $loggingError) {
            // A broken logger must not recursively replace the original response.
        }
    }

    /**
     * Register the exception handling callbacks for the application.
     *
     * @return void
     */
    public function register()
    {


    }

}
